"""LaTeX table rows for the paper, from results/fund_statistics.csv.

    python paper/make_rows.py          # run from the repository root

Each file defines one macro (\TopRows, \BottomRows, \FullRows) rather than holding bare rows,
because \input inside a tabular leaves TeX in a cell at end of file and the next \midrule
raises 'Misplaced \noalign'; a macro expands cleanly at the start of a row.
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
d = (pd.read_csv(ROOT / "results" / "fund_statistics.csv", index_col=0)
       .sort_values("t_log_excess", ascending=False))


def row(name, r):
    name = name.replace("&", r"\&")
    return (f"{name} & {int(r['years'])} & {int(r['CIS_published_%'])} & {r['CIS_arithmetic_numerator_%']:.1f} & "
            f"${r['t_log_excess']:+.2f}$ & {r['CIS_model_consistent_%']:.1f} & {r['p_one_sided_t']:.4f} & "
            f"{r['q_BH']:.3f} & {r['p_adj_max_t_dependence']:.3f}\\\\")


def write(path, macro, frame):
    body = "\n".join(row(i, r) for i, r in frame.iterrows())
    with open(path, "w") as f:
        f.write("%% generated by paper/make_rows.py from results/fund_statistics.csv\n")
        f.write("\\newcommand{\\" + macro + "}{%\n" + body + "%\n}\n")


write(ROOT / "paper" / "table_top_rows.tex", "TopRows", d.head(8))
write(ROOT / "paper" / "table_bottom_rows.tex", "BottomRows", d.tail(5))
write(ROOT / "paper" / "table_full_rows.tex", "FullRows", d)
print(len(d), "rows;", d.head(8).index.tolist(), d.tail(5).index.tolist())
