"""Table rows for the panel-level tests (paper Table 2) from results/dispersion_tests.csv.

    python paper/make_tests_table.py      # run from the repository root; defines \TestRows
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
r = pd.read_csv(ROOT / "results" / "dispersion_tests.csv")
full = r[r.panel == "all 47"].set_index("statistic")
p45 = r[r.funds == 45].set_index("statistic")["p"]
p43 = r[r.funds == 43].set_index("statistic")["p"]

labels = {
    "count": ("Funds above 90\\% confidence", "{:.0f}", 1),
    "max_t": ("Largest $t$ (NYSLRS)", "{:.2f}", 1),
    "min_t": ("Smallest $t$ (LASERS)", "{:.2f}", 1),
    "sd_mean": ("S.d.\\ of mean excess return across plans (\\% p.a.)", "{:.2f}", 100),
    "sd_t": ("S.d.\\ of $t$ across plans", "{:.2f}", 1),
    "sum_t2": ("Sum of squared $t$", "{:.0f}", 1),
    "half_chi2": ("Sum of squared half-sample $z$", "{:.0f}", 1),
    "max_half": ("Largest half-sample $|z|$ (NYSLRS)", "{:.2f}", 1),
}
groups = [("\\emph{Is there skill anywhere?}", ["count", "max_t", "min_t", "sd_mean", "sd_t", "sum_t2"]),
          ("\\emph{Does any plan's skill change?}", ["half_chi2", "max_half"])]


def fmt_p(p):
    return "$<$0.0001" if p < 0.0001 else "{:.4f}".format(p) if p < 0.01 else "{:.3f}".format(p) if p < 0.1 else "{:.2f}".format(p)


lines = []
for title, keys in groups:
    lines.append("\\multicolumn{7}{@{}l}{%s}\\\\" % title)
    for k in keys:
        lab, f, scale = labels[k]
        row = full.loc[k]
        def num(v):
            s = f.format(v * scale)
            return "$%s$" % s if s.startswith("-") else s
        lines.append("%s & %s & %s & %s & %s & %s & %s\\\\" % (
            lab, num(row.observed), num(row.null_mean), num(row.null_q),
            fmt_p(row.p), fmt_p(p45[k]), fmt_p(p43[k])))
body = "\n".join(lines)
with open(ROOT / "paper" / "table_tests_rows.tex", "w") as fh:
    fh.write("%% generated by paper/make_tests_table.py from results/dispersion_tests.csv\n")
    fh.write("\\newcommand{\\TestRows}{%\n" + body + "%\n}\n")
print(body)
# the method-of-moments dispersion of true mean excess returns, full panel and without the four extremes
for label, sub in [("all 47", full), ("43 funds", r[r.funds == 43].set_index("statistic"))]:
    row = sub.loc["sd_mean"]
    tau2 = row.observed ** 2 - row.null_rms ** 2
    print("%s: tau = %.2f%% p.a. (observed sd %.2f%%, null rms %.2f%%)" % (label, 100 * (tau2 ** 0.5 if tau2 > 0 else 0), 100 * row.observed, 100 * row.null_rms))
