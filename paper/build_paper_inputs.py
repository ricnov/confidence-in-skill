"""Everything the paper's tables and figure need, from the cleaned panel (42 programmes).

    python paper/build_paper_inputs.py [data/panel_returns.csv] [B]

Writes results/fund_statistics_clean.csv (per-programme statistics with the max-t adjusted p-values),
paper/table_top_rows.tex, table_bottom_rows.tex, table_full_rows.tex, table_excluded_rows.tex,
paper/table_tests_rows.tex (from results/summary_clean.json, written by scripts/run_everything.py --clean)
and paper/fig_null.pdf. Seed 20261011, B = 50,000 as in the paper.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import cis
from cis.panel import load_panel, clean_panel, log_excess_matrix, DATA_PROBLEMS
from cis.bootstrap import wild_bootstrap, adjusted_p
from cis.multiple import bh_q

ROOT = Path(__file__).resolve().parents[1]
src = sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "data" / "panel_returns.csv")
B = int(sys.argv[2]) if len(sys.argv) > 2 else 50000

panel_all, meta = load_panel(src)
panel = clean_panel(panel_all)

# ---------------------------------------------------------------- per-programme statistics
rows = {}
for fund, d in panel.groupby("fund"):
    d = d.sort_values("year")
    rows[fund] = cis.skill_from_returns(d["actual"].values, d["benchmark"].values)
res = pd.DataFrame(rows).T.join(meta[["sheet_CIS"]])
pub = pd.read_csv(ROOT / "data" / "appendix_III_published.csv").set_index("fund")["cis"]
res["cis_published"] = pub.reindex(res.index)
res["q_t"] = bh_q(res["p_t"].values)
mat = log_excess_matrix(panel)
boot = wild_bootstrap(mat, B=B, seed=20261011)
adj = adjusted_p(boot)
res = res.join(adj[["p_single_up", "p_stepdown_up", "p_single_down"]])
res["p_adj"] = np.where(res["t"] > 0, res["p_single_up"], res["p_single_down"])
res = res.sort_values("t", ascending=False)
out = ROOT / "results" / "fund_statistics_clean.csv"
res.to_csv(out)
print("wrote", out, res.shape)


def row(name, r):
    name = name.replace("&", r"\&")
    return (f"{name} & {int(r['n'])} & {int(round(100 * r['cis_published']))} & {100 * r['cis_arith']:.1f} & "
            f"${r['t']:+.2f}$ & {100 * r['cis_star']:.1f} & {r['p_t']:.4f} & {r['q_t']:.3f} & {r['p_adj']:.3f}\\\\")


def write(path, macro, frame):
    body = "\n".join(row(i, r) for i, r in frame.iterrows())
    with open(path, "w") as f:
        f.write("%% generated by paper/build_paper_inputs.py from results/fund_statistics_clean.csv\n")
        f.write("\\newcommand{\\" + macro + "}{%\n" + body + "%\n}\n")


write(ROOT / "paper" / "table_top_rows.tex", "TopRows", res.head(8))
write(ROOT / "paper" / "table_bottom_rows.tex", "BottomRows", res.tail(5))
write(ROOT / "paper" / "table_full_rows.tex", "FullRows", res)

# the five rows of the article's panel that the cleaned panel leaves out, with their sheet values
ex_rows = {}
for fund, d in panel_all[panel_all["fund"].isin(DATA_PROBLEMS)].groupby("fund"):
    d = d.sort_values("year")
    ex_rows[fund] = cis.skill_from_returns(d["actual"].values, d["benchmark"].values)
ex = pd.DataFrame(ex_rows).T.join(meta[["sheet_CIS"]])
ex["cis_published"] = pub.reindex(ex.index)
reason = {"LASERS": "benchmark column is the S\\&P 500, fiscal 2010--2025",
          "NJ TPAF": "New Jersey Common Pension Fund, second entry",
          "NJDRPB": "New Jersey Common Pension Fund, third entry",
          "PA SERS": "copy of the PA PSERS sheet in 20 of 22 years",
          "NYSCRF": "the NYSLRS fund under a second benchmark"}
lines = []
for f in ["LASERS", "NYSCRF", "NJ TPAF", "NJDRPB", "PA SERS"]:
    r = ex.loc[f]
    lines.append("%s & %d & %d & %.1f & $%+.2f$ & %s\\\\" % (f.replace("&", r"\&"), r["n"], round(100 * r["cis_published"]),
                                                            100 * r["cis_star"], r["t"], reason[f]))
with open(ROOT / "paper" / "table_excluded_rows.tex", "w") as f:
    f.write("%% generated by paper/build_paper_inputs.py\n\\newcommand{\\ExcludedRows}{%\n" + "\n".join(lines) + "%\n}\n")

# ---------------------------------------------------------------- the tests table (Table 2)
S = json.load(open(ROOT / "results" / "summary_clean.json"))
D = S["dispersion"]
labels = {
    "count": ("Programmes above 90\\% confidence", "{:.0f}", 1),
    "max_t": ("Largest $t$ (NYSLRS)", "{:.2f}", 1),
    "min_t": ("Smallest $t$ (DAL F\\&P)", "{:.2f}", 1),
    "sd_mean": ("S.d.\\ of mean excess return across programmes (\\% p.a.)", "{:.2f}", 100),
    "sd_t": ("S.d.\\ of $t$ across programmes", "{:.2f}", 1),
    "sum_t2": ("Sum of squared $t$", "{:.0f}", 1),
    "half_chi2": ("Sum of squared half-sample $z$", "{:.0f}", 1),
    "max_half": ("Largest half-sample $|z|$ (NYSLRS)", "{:.2f}", 1),
}
groups = [("\\emph{Is there skill anywhere?}", ["count", "max_t", "min_t", "sd_mean", "sd_t", "sum_t2"]),
          ("\\emph{Does any programme's skill change?}", ["half_chi2", "max_half"])]


def fmt_p(p):
    return "$<$0.0001" if p < 0.0001 else "{:.4f}".format(p) if p < 0.01 else "{:.3f}".format(p) if p < 0.1 else "{:.2f}".format(p)


tl = []
for title, keys in groups:
    tl.append("\\multicolumn{7}{@{}l}{%s}\\\\" % title)
    for k in keys:
        lab, f, scale = labels[k]
        full = D["all"]["table"][k]

        def num(v):
            s_ = f.format(v * scale)
            return "$%s$" % s_ if s_.startswith("-") else s_
        tl.append("%s & %s & %s & %s & %s & %s & %s\\\\" % (
            lab, num(full["observed"]), num(full["null_mean"]), num(full["null_q"]), fmt_p(full["p"]),
            fmt_p(D["without_top_bottom"]["table"][k]["p"]), fmt_p(D["without_extremes"]["table"][k]["p"])))
P = S["persistence"]
tl.append("\\multicolumn{7}{@{}l}{\\emph{Is skill persistent across programmes?}}\\\\")
tl.append("Rank correlation of first- and second-half mean excess returns & %.2f & %.2f & %.2f & %s & & \\\\" % (
    P["spearman"], P.get("spearman_null_mean", -0.01), P["spearman_null_95"], fmt_p(P["spearman_P"])))  # null mean -0.008 (20,000 draws)
with open(ROOT / "paper" / "table_tests_rows.tex", "w") as f:
    f.write("%% generated by paper/build_paper_inputs.py from results/summary_clean.json\n\\newcommand{\\TestRows}{%\n" + "\n".join(tl) + "%\n}\n")
print("tables written; tau:", {k: D[k]["tau_pct"] for k in D})

# ---------------------------------------------------------------- the figure
T, t_obs, n_obs = boot["T"], boot["t"], boot["n"]
m = t_obs.size
counts = (stats.norm.cdf(T) > 0.9).sum(axis=1)
maxt = T.max(axis=1)
rng = np.random.default_rng(20261012)
Sm = stats.t.rvs(df=n_obs - 1, size=(20000, m), random_state=rng)
counts_ind = (stats.norm.cdf(Sm) > 0.9).sum(axis=1)
maxt_ind = Sm.max(axis=1)
obs_count = int((stats.norm.cdf(t_obs) > 0.9).sum())
obs_max = float(t_obs.max())
top_fund = boot["funds"][int(np.argmax(t_obs))]
BLUE, GRAY, INK, MUTED = "#2a78d6", "#c9ccd1", "#0b0b0b", "#52514e"
plt.rcParams.update({"font.family": "serif", "font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                     "xtick.color": MUTED, "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False})
fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.8))
ax = axes[0]
bins = np.arange(-0.5, 36.5, 1)
ax.hist(counts, bins=bins, density=True, color=GRAY, edgecolor="white", linewidth=0.5, label="year-cluster bootstrap")
h_ind, _ = np.histogram(counts_ind, bins=bins, density=True)
ax.step(bins[:-1] + 0.5, h_ind, where="mid", color=MUTED, linewidth=1.2, linestyle="--", label="independent programmes")
ax.axvline(obs_count, color=BLUE, linewidth=2)
ax.text(obs_count + 0.6, ax.get_ylim()[1] * 0.92, "observed: %d" % obs_count, color=INK, fontsize=8.5, va="top")
ax.set_xlabel("programmes above 90% confidence under the null"); ax.set_ylabel("probability"); ax.set_xlim(-0.5, 35.5)
ax.legend(frameon=False, fontsize=8, loc="center right")
ax = axes[1]
bins = np.linspace(1.0, 6.0, 51)
ax.hist(maxt, bins=bins, density=True, color=GRAY, edgecolor="white", linewidth=0.5)
h_ind, _ = np.histogram(maxt_ind, bins=bins, density=True)
ax.step(0.5 * (bins[:-1] + bins[1:]), h_ind, where="mid", color=MUTED, linewidth=1.2, linestyle="--")
ax.axvline(obs_max, color=BLUE, linewidth=2)
ax.text(obs_max + 0.08, ax.get_ylim()[1] * 0.92, "%s: %.2f" % (top_fund, obs_max), color=INK, fontsize=8.5, va="top")
ax.set_xlabel("largest $t$ of the %d programmes under the null" % m); ax.set_ylabel("density"); ax.set_xlim(1.0, 6.0)
fig.tight_layout(w_pad=2.0)
fig.savefig(ROOT / "paper" / "fig_null.pdf"); fig.savefig(ROOT / "paper" / "fig_null.png", dpi=200)
print("figure written; count 95/99:", np.percentile(counts, [95, 99]), "max t 95/99:", np.percentile(maxt, [95, 99]).round(2),
      "P(count>=obs) %.4f P(max>=obs) %.4f" % ((counts >= obs_count).mean(), (maxt >= obs_max).mean()))
