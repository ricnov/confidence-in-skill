"""Table rows for the nine further plans (paper Section 4.7): defines \ExtraRows.

    python paper/make_extra_table.py data/panel_returns_extended.csv
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import cis

ROOT = Path(__file__).resolve().parents[1]
ext = pd.read_csv(sys.argv[1] if len(sys.argv) > 1 else ROOT / "data" / "panel_returns_extended.csv")
names = ["SWIB", "INPRS", "Ohio PERS", "Colorado PERA", "Maine PERS", "IL TRS", "Houston POPS", "CT TRS", "Iowa PERS"]
labels = {"SWIB": "SWIB Core Fund", "INPRS": "Indiana PRS", "Ohio PERS": "Ohio PERS", "Colorado PERA": "Colorado PERA",
          "Maine PERS": "Maine PERS", "IL TRS": "Illinois TRS", "Houston POPS": "Houston POPS", "CT TRS": "Connecticut TRS", "Iowa PERS": "Iowa PERS"}
rows = []
for f in names:
    d = ext[ext.fund == f].sort_values("year")
    s = cis.skill_from_returns(d.actual.values, d.benchmark.values)
    sd = np.sqrt(s["n"]) * s["gap_star"] / s["t"] if s["t"] != 0 else np.nan
    rows.append((f, s, d.year.min(), d.year.max(), sd))
rows.sort(key=lambda r: -r[1]["t"])
lines = []
for f, s, y0, y1, sd in rows:
    lines.append("%s & %d--%d & %d & $%+.0f$ & %.2f & $%+.2f$ & %.1f & %.4f\\\\" % (
        labels[f], y0, y1, s["n"], 1e4 * s["gap_star"], 100 * sd, s["t"], 100 * s["cis_star"], s["p_t"]))
with open(ROOT / "paper" / "table_extra_rows.tex", "w") as fh:
    fh.write("%% generated by paper/make_extra_table.py\n\\newcommand{\\ExtraRows}{%\n" + "\n".join(lines) + "%\n}\n")
print("\n".join(lines))
